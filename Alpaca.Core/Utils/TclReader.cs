        #region helpers

        private Point3d NodeAt(string[] tokens, int index)
        {
            int tag = Tag(tokens, index);
            if (!_nodes.TryGetValue(tag, out var position))
                throw new InvalidOperationException($"node {tag} is not in the file.");
            return position;
        }

        private Mesh VerticesOf(string[] tokens, int firstIndex, int vertexCount)
        {
            var mesh = new Mesh();
            for (int i = 0; i < vertexCount; i++)
                mesh.Vertices.Add(NodeAt(tokens, firstIndex + i));
            return mesh;
        }

        /// <summary>A single shell face, three or four corners, in the order the element lists them.</summary>
        private Mesh ShellMeshOf(string[] tokens, int firstIndex, int vertexCount)
        {
            var mesh = VerticesOf(tokens, firstIndex, vertexCount);

            if (vertexCount == 3)
                mesh.Faces.AddFace(0, 1, 2);
            else
                mesh.Faces.AddFace(0, 1, 2, 3);

            return mesh;
        }

        /// <summary>
        /// A closed tetrahedron or hexahedron. The faces are wound exactly as Utils.CleanTetrahedron
        /// and Utils.CleanHexahedron wind them, because the element already stores its nodes in the
        /// order those produced - and because a solid whose normals point inwards reports a negative
        /// volume, which would turn up as a negative mass.
        /// </summary>
        private Mesh SolidMeshOf(string[] tokens, int firstIndex, int vertexCount)
        {
            var mesh = VerticesOf(tokens, firstIndex, vertexCount);

            if (vertexCount == 4)
            {
                mesh.Faces.AddFace(0, 2, 1);
                mesh.Faces.AddFace(0, 2, 3);
                mesh.Faces.AddFace(0, 3, 1);
                mesh.Faces.AddFace(1, 3, 2);
            }
            else
            {
                mesh.Faces.AddFace(0, 1, 2, 3);
                mesh.Faces.AddFace(4, 5, 6, 7);
                mesh.Faces.AddFace(1, 2, 6, 5);
                mesh.Faces.AddFace(0, 3, 7, 4);
                mesh.Faces.AddFace(0, 1, 5, 4);
                mesh.Faces.AddFace(3, 2, 6, 7);
            }

            mesh.FaceNormals.ComputeFaceNormals();
            mesh.UnifyNormals();

            return mesh;
        }

        private IUniaxialSection SectionAt(string[] tokens, int index, int elementTag)
        {
            int tag = Tag(tokens, index);
            if (!_uniaxialSections.TryGetValue(tag, out var section))
                throw new InvalidOperationException($"element {elementTag} refers to section {tag}, which is not an \"section Elastic\" in the file.");
            return section;
        }

        private IMultiDimensionSection PlateSectionAt(string[] tokens, int index, int elementTag)
        {
            int tag = Tag(tokens, index);
            if (!_plateSections.TryGetValue(tag, out var section))
                throw new InvalidOperationException($"element {elementTag} refers to section {tag}, which is not a \"section PlateFiber\" in the file.");
            return section;
        }

        /// <summary>Reads consecutive numbers from <paramref name="firstIndex"/> until a non-number appears.</summary>
        private static List<double> ReadTrailingNumbers(string[] tokens, int firstIndex)
        {
            var values = new List<double>();
            for (int i = firstIndex; i < tokens.Length; i++)
            {
                if (!TryNumber(tokens[i], out double value))
                    break;
                values.Add(value);
            }
            return values;
        }

        private static Vector3d Vector(List<double> values, int firstIndex)
        {
            return new Vector3d(values[firstIndex], values[firstIndex + 1], values[firstIndex + 2]);
        }

        private void Warn(string message)
        {
            if (!_warnings.Contains(message))
                _warnings.Add(message);
        }

